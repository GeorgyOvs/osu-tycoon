const place = (p: string): string => {
  const single = p.match(/^(\d+)(?:st|nd|rd|th)$/)
  if (single) return `${single[1]}-е место`
  const range = p.match(/^(\d+)(?:st|nd|rd|th)–(\d+)(?:st|nd|rd|th)$/)
  return range ? `${range[1]}–${range[2]} место` : p
}

const REASONS: Record<string, string> = {
  retired: 'завершил карьеру',
  'drifted away': 'отдалился от команды',
  'joined another team': 'перешёл в другую команду',
  'still sees you as a rival': 'всё ещё видит в вас соперника',
  'wants a stronger team': 'хочет команду посильнее',
  "isn't interested right now": 'сейчас не заинтересован',
}
const why = (r: string) => REASONS[r] ?? r

