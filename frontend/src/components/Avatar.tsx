import { useRef } from 'react'
import { usePersisted } from '../usePersisted'
import { t } from '../i18n'

function hash(text: string): number {
  let h = 2166136261
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

function rng(seed: number) {
  let s = seed || 1
  return () => {
    s ^= s << 13
    s ^= s >>> 17
    s ^= s << 5
    return (s >>> 0) / 4294967296
  }
}

/** A deterministic cartoon face: skin, hair, eyes and a headset, all drawn from the name. */
export function GeneratedAvatar({ seed, size = 40, className = '' }: { seed: string; size?: number; className?: string }) {
  const r = rng(hash(seed))
  const hue = Math.floor(r() * 360)
  const skin = ['#f6d5b8', '#e8b998', '#c98d65', '#8d5a3b', '#fbe3cf'][Math.floor(r() * 5)]
  const hair = ['#2b1d16', '#6b3f1d', '#d9a441', '#c4412f', '#1d1d24', '#f0f0f0', '#ff66aa', '#4aa3ff'][Math.floor(r() * 8)]
  const style = Math.floor(r() * 4)
  const eyes = Math.floor(r() * 3)
  const headset = r() < 0.55
  const glasses = r() < 0.3
  const bg = `hsl(${hue} 45% 28%)`
  const bg2 = `hsl(${(hue + 40) % 360} 55% 38%)`
  const id = `av${hash(seed)}`
  return (
    <svg viewBox="0 0 64 64" width={size} height={size} className={`shrink-0 rounded-full ${className}`} aria-hidden>
      <defs>
        <linearGradient id={id} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor={bg} />
          <stop offset="1" stopColor={bg2} />
        </linearGradient>
      </defs>
      <rect width="64" height="64" fill={`url(#${id})`} />
      <path d="M10 64c0-12 9-19 22-19s22 7 22 19z" fill={`hsl(${(hue + 180) % 360} 40% 45%)`} />
      <rect x="27" y="38" width="10" height="9" rx="3" fill={skin} />
      {style === 0 && <path d="M17 30c-2-14 8-20 16-20s17 6 14 20c-3-8-8-11-15-11s-12 3-15 11z" fill={hair} />}
      <ellipse cx="32" cy="30" rx="12.5" ry="14" fill={skin} />
      {style === 0 && <path d="M19 28c0-10 6-14 13-14s14 4 13 14c-3-5-8-8-13-8s-10 3-13 8z" fill={hair} />}
      {style === 1 && <path d="M18 26c1-12 8-16 14-16s13 4 14 16c-4-3-8-6-14-6s-10 3-14 6z" fill={hair} />}
      {style === 2 && <path d="M18 30c-3-16 6-22 14-22s17 6 14 22c-1-7-2-10-5-12-6 3-14 3-18 0-3 2-4 6-5 12z" fill={hair} />}
      {style === 3 && <path d="M19 22c3-8 8-10 13-10s10 2 13 10c-5-2-9-3-13-3s-8 1-13 3z" fill={hair} />}
      {eyes === 0 && (
        <>
          <circle cx="27" cy="31" r="1.8" fill="#222" />
          <circle cx="37" cy="31" r="1.8" fill="#222" />
        </>
      )}
      {eyes === 1 && (
        <>
          <path d="M24.5 31h5M34.5 31h5" stroke="#222" strokeWidth="2" strokeLinecap="round" />
        </>
      )}
      {eyes === 2 && (
        <>
          <circle cx="27" cy="31" r="2.4" fill="#fff" />
          <circle cx="37" cy="31" r="2.4" fill="#fff" />
          <circle cx="27.4" cy="31.2" r="1.2" fill="#222" />
          <circle cx="37.4" cy="31.2" r="1.2" fill="#222" />
        </>
      )}
      <path d="M28 37.5c2 1.6 6 1.6 8 0" stroke="#7a3b2a" strokeWidth="1.4" fill="none" strokeLinecap="round" />
      {glasses && (
        <g fill="none" stroke="#111" strokeWidth="1.2">
          <circle cx="27" cy="31" r="4.2" />
          <circle cx="37" cy="31" r="4.2" />
          <path d="M31.2 31h1.6" />
        </g>
      )}
      {headset && (
        <g>
          <path d="M18 31c0-10 6-16 14-16s14 6 14 16" fill="none" stroke="#e5e5e5" strokeWidth="2.2" />
          <rect x="15.5" y="29" width="5" height="9" rx="2.2" fill="#ff66aa" />
          <rect x="43.5" y="29" width="5" height="9" rx="2.2" fill="#ff66aa" />
        </g>
      )}
    </svg>
  )
}

/** The player's own avatar: generated by default, replaceable with an uploaded picture (kept in this browser). */
export function PlayerAvatar({ playerId, name, size = 72, editable = false }: { playerId: number; name: string; size?: number; editable?: boolean }) {
  const [image, setImage] = usePersisted<string | null>(`avatar.${playerId}`, null)
  const [variant, setVariant] = usePersisted<number>(`avatar.variant.${playerId}`, 0)
  const input = useRef<HTMLInputElement>(null)

  const onFile = (file: File | undefined) => {
    if (!file) return
    const reader = new FileReader()
    reader.onload = () => {
      const img = new Image()
      img.onload = () => {
        const side = Math.min(img.width, img.height)
        const canvas = document.createElement('canvas')
        canvas.width = canvas.height = 160
        canvas.getContext('2d')?.drawImage(img, (img.width - side) / 2, (img.height - side) / 2, side, side, 0, 0, 160, 160)
        setImage(canvas.toDataURL('image/jpeg', 0.85))
      }
      img.src = String(reader.result)
    }
    reader.readAsDataURL(file)
  }

  const face = image ? (
    <img src={image} alt="" width={size} height={size} className="shrink-0 rounded-full object-cover" style={{ width: size, height: size }} />
  ) : (
    <GeneratedAvatar seed={`${name}:${playerId}:${variant}`} size={size} />
  )
  if (!editable) return face
  return (
    <div className="group relative shrink-0" style={{ width: size, height: size }}>
      {face}
      <div className="absolute inset-0 flex items-end justify-center gap-1 rounded-full bg-black/0 pb-1 text-[10px] opacity-0 transition group-hover:bg-black/50 group-hover:opacity-100">
        <button type="button" title={t('Upload a picture')} onClick={() => input.current?.click()} className="rounded bg-black/70 px-1.5 py-0.5">
          ⬆
        </button>
        <button
          type="button"
          title={t('Generate another avatar')}
          onClick={() => {
            setImage(null)
            setVariant(variant + 1)
          }}
          className="rounded bg-black/70 px-1.5 py-0.5"
        >
          ⟳
        </button>
      </div>
      <input ref={input} type="file" accept="image/*" hidden onChange={(e) => onFile(e.target.files?.[0])} />
    </div>
  )
}
